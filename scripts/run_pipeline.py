"""
Unified orchestration script for the Theseus data pipeline.

Usage::

    python -m scripts.run_pipeline [--repo NAME] [--reprocess TARGET] [--update-survivor]

Runs the pipeline stages in sequence on one or more repositories:

1. **Engine Analysis** (snapshot and fossil generation via compiled Rust engine)
2. **Fossil Verification** (validate Genesis and Survivor fossils produced by engine)
3. **Cleanup** (future-year filtering and minification via execute_full_cleanup_and_graph_generation)

Fossil data model
-----------------
See ``_data_io.py`` for the canonical fossil schema definition.
"""

# pylint: disable=too-many-locals,too-many-branches,too-many-statements,broad-exception-caught
import argparse
import logging
import os
import sys
import time

from scripts._data_io import load_fossils
from scripts._utils import load_config
from scripts.analyse_repository import process_repository
from scripts.cleanup_data import (
    execute_full_cleanup_and_graph_generation as run_cleanup,
)

logger = logging.getLogger(__name__)


def run_pipeline(
    repo: str | None = None,
    reprocess: str | None = None,
    update_survivor: bool = False,
) -> bool:
    """
    Run the full pipeline (analyse -> verify fossils -> cleanup) for all repositories.

    :param repo: Optional repository name to process (None = all repos).
    :param reprocess: Optional target ('all', 'last', or 'YYYY-MM') to force re-process.
    :param update_survivor: Kept for CLI compatibility. Survivor fossils are now
        generated automatically in the unified engine pass.
    :return: ``True`` if any stage failed, ``False`` otherwise.
    """
    _ = update_survivor
    config = load_config()
    data_dir = config.get("dataDir", "./data")
    os.makedirs(data_dir, exist_ok=True)
    os.makedirs(os.path.join(data_dir, "raw"), exist_ok=True)
    os.makedirs(os.path.join(data_dir, "processed"), exist_ok=True)

    # Build target lists from config
    all_repos: list[dict] = config.get("repositories", [])
    if not all_repos:
        logger.error("No repositories found in configuration.")
        return True

    if repo:
        selected = [r for r in all_repos if r.get("name") == repo]
        if not selected:
            logger.error("Unknown repository '%s'.", repo)
            return True
        logger.info("Pipeline running for single repository: %s", repo)
    else:
        selected = all_repos
        logger.info("Pipeline running for %d repositories.", len(selected))

    had_failures = False

    # ── Stage 1: Analyse & Fossil Extraction ───────────────────────────
    logger.info("═══ STAGE 1: Snapshot and fossil analysis ═══")
    for repo_info in selected:
        repo_slug = repo_info.get("repo", "")
        repo_name = repo_info.get("name", "")
        if not repo_slug or not repo_name:
            logger.warning("Skipping repo entry with missing slug/name: %s", repo_info)
            continue

        logger.info("  Analysing %s (%s)...", repo_name, repo_slug)
        try:
            process_repository(repo_slug, data_dir, reprocess)
            logger.info("  ✓ %s: engine analysis complete.", repo_name)
        except Exception as e:  # noqa: BLE001
            logger.error("  ✗ %s: engine analysis failed: %s", repo_name, e)
            had_failures = True

    # ── Stage 2: Fossil Verification ───────────────────────────────────
    logger.info("═══ STAGE 2: Fossil verification ═══")

    def _is_valid_fossil(record: dict | None) -> bool:
        if not isinstance(record, dict):
            return False
        return bool(record.get("file") and record.get("content") and record.get("line", 0) > 0)

    for r in selected:
        repo_name = r.get("name", "")
        fossil_file = os.path.join(data_dir, "raw", f"{repo_name}_fossils.json")
        fossils = load_fossils(fossil_file)
        if _is_valid_fossil(fossils.get("genesis")) and _is_valid_fossil(fossils.get("survivor")):
            logger.info("  ✓ %s: fossils verified (generated by engine).", repo_name)
        else:
            logger.error("  ✗ %s: fossil verification failed (missing or incomplete).", repo_name)
            had_failures = True

    # ── Stage 3: Cleanup ───────────────────────────────────────────────
    logger.info("═══ STAGE 3: Data cleanup ═══")
    try:
        cleanup_errors = run_cleanup(data_dir)
        if cleanup_errors:
            had_failures = True
        else:
            logger.info("  ✓ Cleanup complete.")
    except Exception as e:  # noqa: BLE001
        logger.error("  ✗ Cleanup stage failed: %s", e)
        had_failures = True

    return had_failures


def main() -> None:
    """
    Entry point for the unified pipeline runner.

    CLI flags
    ---------
    --repo NAME          Process only this repository.
    --reprocess TARGET   Re-process 'all', 'last', or a specific snapshot period.
    --update-survivor    Kept for backward compatibility (survivor fossils are
                         extracted automatically in the engine pass).
    """
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s [%(levelname)s] %(message)s",
        datefmt="%Y-%m-%d %H:%M:%S",
    )

    parser = argparse.ArgumentParser(
        description="Run the full Theseus pipeline: engine analysis and data cleanup."
    )
    parser.add_argument(
        "--repo",
        metavar="NAME",
        default=None,
        help="Only process this repository (e.g. 'react'). If omitted, all repos are processed.",
    )
    parser.add_argument(
        "--reprocess",
        metavar="TARGET",
        default=None,
        help=(
            "Re-process a target. Pass 'all' to wipe and rebuild, 'last' for the latest "
            "period, or a specific period like '2023-06'."
        ),
    )
    parser.add_argument(
        "--update-survivor",
        action="store_true",
        help="Kept for backward compatibility; fossils are now extracted in the engine pass.",
    )
    args = parser.parse_args()

    overall_start = time.perf_counter()
    had_errors = run_pipeline(
        repo=args.repo,
        reprocess=args.reprocess,
        update_survivor=args.update_survivor,
    )
    elapsed = time.perf_counter() - overall_start

    if had_errors:
        logger.error("Pipeline finished with errors (%.2f seconds).", elapsed)
        sys.exit(1)

    logger.info("Pipeline completed successfully (%.2f seconds).", elapsed)


if __name__ == "__main__":
    main()
